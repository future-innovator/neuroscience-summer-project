import numpy as np

nums = np.array([5, 10, 15, 20, 25])

print(f"The mean of nums is: {nums.mean()}")
print(f"The max of nums is: {nums.max()}")
print(f"The min of nums is: {nums.min()}")
print(f"The sum of nums is: {nums.sum()}")

#The mean represents the average value of a dataset (can be though of as its "center of mass"), skewed by extremely high and low data points
