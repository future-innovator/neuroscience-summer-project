import numpy as np

nums = np.array([5, 10, 15, 20, 25])

print(f"nums * 2: {nums *2}")

print(f"nums + 100: {nums + 100}")

print(f"nums squared: {nums ** 2}")

#NumPy does not require a loop for these operations because it is applying the operation to the entire array as opposed to each element one at a times